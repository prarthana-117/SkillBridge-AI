async function renderJobs() {
  const { jobs } = await api("/api/jobs");
  view.innerHTML = `
    ${head("Job Matches", "Openings ranked by how well your current skills fit. <span class='small'>(Sample listings for demo)</span>")}
    <div class="filters">
      <select id="fType"><option value="">All types</option><option>Full-time</option><option>Internship</option></select>
      <select id="fMin"><option value="0">Any match</option><option value="45">45%+</option><option value="75">75%+</option></select>
      <select id="fSaved"><option value="">All jobs</option><option value="1">Saved only</option></select>
    </div>
    <div class="grid jobs-grid" id="jobsGrid"></div>`;

  const draw = () => {
    const type = document.getElementById("fType").value;
    const min = +document.getElementById("fMin").value;
    const saved = document.getElementById("fSaved").value;
    const list = jobs.filter(j => (!type || j.type === type) && j.match >= min && (!saved || j.saved));
    document.getElementById("jobsGrid").innerHTML = list.length ? list.map(j => `
      <div class="card job">
        <div style="display:flex;justify-content:space-between;gap:.5rem">
          <div><h3>${esc(j.title)}</h3><div class="co">${esc(j.company)} · ${esc(j.location)}</div></div>
          <button class="save-btn ${j.saved ? "on" : ""}" data-save="${j.id}" aria-label="Save job">${j.saved ? "★" : "☆"}</button>
        </div>
        <div class="match"><span>${j.match}% match</span><div class="bar"><span style="width:${j.match}%"></span></div></div>
        ${j.have.length ? `<div class="sec">YOU HAVE</div><div class="chips">${j.have.map(s => `<span class="chip good">${esc(s)}</span>`).join("")}</div>` : ""}
        ${j.need.length ? `<div class="sec">TO LEARN</div><div class="chips">${j.need.map(s => `<span class="chip warn">${esc(s)}</span>`).join("")}</div>` : ""}
        <div class="job-foot"><span class="chip">${esc(j.type)}</span>
          ${j.match >= 75 ? '<span class="chip good">Ready to apply</span>' : `<a href="#roadmap" data-go="roadmap" class="small">Close the gap →</a>`}</div>
      </div>`).join("") : '<div class="card empty">No jobs match these filters.</div>';
  };
  view.querySelectorAll(".filters select").forEach(s => s.addEventListener("change", draw));
  document.getElementById("jobsGrid").addEventListener("click", async e => {
    const b = e.target.closest("[data-save]");
    if (!b) return;
    const job = jobs.find(j => j.id === +b.dataset.save);
    job.saved = !job.saved;
    await api("/api/jobs/save", { job_id: job.id, saved: job.saved });
    toast(job.saved ? "Job saved" : "Removed from saved");
    draw();
  });
  draw();
}

