/* ----- boot & navigation ------------------------------------------------ */
async function boot() {
  [state.me, state.catalog] = await Promise.all([api("/api/me"), api("/api/catalog")]);
  document.getElementById("userName").textContent = state.me.user.full_name;
  document.getElementById("userEmail").textContent = state.me.user.email;

  const initial = location.hash.slice(1);
  go(VIEWS[initial] ? initial : state.me.profile.is_new ? "profile" : "dashboard");
}

function go(name) {
  if (!VIEWS[name]) name = "dashboard";
  history.replaceState(null, "", "#" + name);
  document.querySelectorAll("#sideNav button").forEach(b => b.classList.toggle("active", b.dataset.view === name));
  document.getElementById("sidebar").classList.remove("open");
  view.innerHTML = '<div class="loading">Loading…</div>';
  window.scrollTo(0, 0);
  VIEWS[name]().catch(err => { view.innerHTML = `<div class="error-box">${esc(err.message)}</div>`; });
}

document.getElementById("sideNav").addEventListener("click", e => {
  const b = e.target.closest("button[data-view]");
  if (b) go(b.dataset.view);
});
window.addEventListener("hashchange", () => go(location.hash.slice(1)));
document.getElementById("menuBtn").addEventListener("click", () =>
  document.getElementById("sidebar").classList.toggle("open"));
document.getElementById("logoutBtn").addEventListener("click", async () => {
  await api("/api/logout", {});
  location.href = "/";
});
view.addEventListener("click", e => {
  const link = e.target.closest("[data-go]");
  if (link) { e.preventDefault(); go(link.dataset.go); }
});

const skillName = id => state.catalog.skills.find(s => s.id === id)?.name || id;
const levelName = n => state.catalog.levels[n] || "None";
const head = (title, sub, extra = "") =>
  `<div class="page-head"><div><h1>${title}</h1><p>${sub}</p></div>${extra}</div>`;
const statusChip = s => ({
  strong: '<span class="chip good">✓ On target</span>',
  developing: '<span class="chip warn">Developing</span>',
  missing: '<span class="chip bad">Missing</span>',
}[s]);
const aiBadge = () => state.catalog.ai.enabled
  ? `<span class="chip primary" title="Answers are generated by Claude">${icon("sparkles", 13)} Powered by Claude</span>`
  : '<span class="chip" title="Set ANTHROPIC_API_KEY on the server to enable Claude">Offline AI mode</span>';
const weightChip = w => `<span class="chip ${w === "core" ? "primary" : ""}">${w}</span>`;

