function skillMeter(s) {
  return `<div class="skill-row">
    <span>${esc(s.name)}</span>
    <div class="meter"><div class="have" style="width:${s.have * 20}%"></div><div class="target" style="left:${s.target * 20}%"></div></div>
    <span class="small muted" style="text-align:right">${s.have}/${s.target}</span>
  </div>`;
}
const matchClass = m => m >= 75 ? "good" : m >= 45 ? "warn" : "bad";

function activityRow(a) {
  const ico = icon({ resume: "file", interview: "mic", task: "checkCircle" }[a.kind] || "check", 16);
  const label = a.kind === "task" ? `Completed ${taskLabel(a.label)}` : a.label;
  const when = new Date(a.created_at.replace(" ", "T") + "Z").toLocaleDateString(undefined, { month: "short", day: "numeric" });
  return `<div class="list-item"><span class="with-icon">${ico} ${esc(label)}</span>
    <span class="small muted">${a.score != null ? `<strong>${a.score}</strong> · ` : ""}${when}</span></div>`;
}
function taskLabel(id) {
  const [skill, kind] = id.split(":");
  if (skill === "career") return "a career-launch task";
  return `${skillName(skill)} ${kind}`;
}

/* ======================================================================
   Profile & skill self-rating
   ====================================================================== */
async function renderProfile() {
  const profile = await api("/api/profile");
  const form = { ...profile, skills: { ...profile.skills } };

  view.innerHTML = `
    ${head("My Profile & Skills", "Tell SkillBridge where you want to go and what you already know.")}
    ${profile.is_new ? `<div class="banner"><span class="big">${icon("sparkles", 26)}</span><div><strong>Welcome to SkillBridge AI</strong>
      <div class="small">Pick a target role and rate your skills — your analysis, roadmap and job matches are built from this.</div></div></div>` : ""}
    <div class="card" style="margin-bottom:1rem">
      <h3>1. Target role</h3>
      <div class="grid role-pick" id="rolePick"></div>
    </div>
    <div class="card" style="margin-bottom:1rem">
      <h3>2. About you</h3>
      <div class="form-row">
        <div class="field"><label for="status">Current status</label>
          <select id="status">${state.catalog.statuses.map(s => `<option ${s === form.current_status ? "selected" : ""}>${s}</option>`).join("")}</select></div>
        <div class="field"><label for="hours">Hours you can study per week: <span id="hoursVal">${form.hours_per_week}</span></label>
          <input type="range" id="hours" min="2" max="40" value="${form.hours_per_week}" style="width:100%;accent-color:var(--primary)"></div>
      </div>
    </div>
    <div class="card" id="skillsCard">
      <h3>3. Rate your skills</h3>
      <p class="small muted">1 Beginner · 2 Basic · 3 Intermediate · 4 Advanced · 5 Expert. Click again to clear.
        Tip: the <a href="#resume" data-go="resume">Resume Analyzer</a> can fill this in for you.</p>
      <div id="roleSkills"></div>
      <details class="more"><summary>Other skills (transferable)</summary><div id="otherSkills"></div></details>
    </div>
    <div class="sticky-save"><button class="btn lg" id="saveProfile">Save & analyze →</button></div>`;

  const drawRoles = () => {
    document.getElementById("rolePick").innerHTML = state.catalog.roles.map(r => `
      <button type="button" class="role-opt ${r.id === form.target_role ? "selected" : ""}" data-role="${r.id}">
        ${roleIcon(r.id, 20)}<span class="t">${esc(r.title)}</span><span class="d">${esc(r.summary)}</span>
      </button>`).join("");
  };
  const rateRow = s => `<div class="rate-row"><div class="nm">${esc(s.name)}<small>${esc(s.category)}</small></div>
    <div class="levels" data-skill="${s.id}">${[1, 2, 3, 4, 5].map(n =>
      `<button type="button" data-level="${n}" class="${(form.skills[s.id] || 0) >= n ? "on" : ""}" title="${levelName(n)}">${n}</button>`).join("")}</div></div>`;
  const drawSkills = () => {
    const ids = state.catalog.roles.find(r => r.id === form.target_role).skills;
    document.getElementById("roleSkills").innerHTML =
      ids.map(id => rateRow(state.catalog.skills.find(s => s.id === id))).join("");
    document.getElementById("otherSkills").innerHTML =
      state.catalog.skills.filter(s => !ids.includes(s.id)).map(rateRow).join("");
  };
  drawRoles();
  drawSkills();

  view.querySelector("#rolePick").addEventListener("click", e => {
    const b = e.target.closest("[data-role]");
    if (!b) return;
    form.target_role = b.dataset.role;
    drawRoles();
    drawSkills();
  });
  document.getElementById("skillsCard").addEventListener("click", e => {
    const b = e.target.closest(".levels button");
    if (!b) return;
    const skill = b.parentElement.dataset.skill, n = +b.dataset.level;
    if (form.skills[skill] === n) delete form.skills[skill]; else form.skills[skill] = n;
    b.parentElement.querySelectorAll("button").forEach(x => x.classList.toggle("on", (form.skills[skill] || 0) >= +x.dataset.level));
  });
  const hours = document.getElementById("hours");
  hours.addEventListener("input", () => document.getElementById("hoursVal").textContent = hours.value);

  document.getElementById("saveProfile").addEventListener("click", async () => {
    await api("/api/profile", {
      target_role: form.target_role,
      current_status: document.getElementById("status").value,
      hours_per_week: +hours.value,
      skills: form.skills,
    });
    state.me = await api("/api/me");
    toast("Profile saved — analysis updated");
    go("gap");
  });
}

