async function renderRoadmap(data) {
  const r = data || await api("/api/roadmap");
  const phaseIcon = { Foundation: "layers", Build: "wrench", Polish: "sparkles", "Career Launch": "rocket" };
  const kindChip = { learn: "Learn", practice: "Practice", project: "Project", career: "Career" };

  view.innerHTML = `
    ${head("Learning Roadmap", `${r.total_weeks} weeks to ${esc(r.role)} at ${r.hours_per_week}h/week`,
      `<button class="btn ghost" data-go="profile">Adjust hours</button>`)}
    <div class="card" style="margin-bottom:1.5rem">
      <div style="display:flex;justify-content:space-between;margin-bottom:.5rem"><strong>Overall progress</strong>
        <span>${r.done_tasks}/${r.total_tasks} tasks · <strong>${r.percent}%</strong></span></div>
      <div class="bar" style="height:12px"><span style="width:${r.percent}%"></span></div>
    </div>
    ${r.phases.map(p => `<div class="phase">
      <div class="phase-title"><span class="phase-icon">${icon(phaseIcon[p.name], 18)}</span><h2>${p.name}</h2>
        <span class="chip">${p.items.length} ${p.items.length === 1 ? "track" : "tracks"}</span></div>
      ${p.items.map(item => `<div class="card road-item ${item.done ? "done" : ""}">
        <div class="road-head">
          <div><h3>${item.done ? `<span class="done-mark">${icon("checkCircle", 18)}</span>` : ""}${esc(item.skill)}</h3>
            ${item.target ? `<div class="small muted">${levelName(item.have)} → ${levelName(item.target)} · ~${item.hours}h</div>` : ""}</div>
          ${item.target ? weightChip(item.weight) : ""}
        </div>
        ${item.tasks.map(t => `<label class="task ${t.done ? "done" : ""}">
          <input type="checkbox" data-task="${t.id}" ${t.done ? "checked" : ""}>
          <span class="tt">${esc(t.title)}</span>
          <span class="meta"><span class="chip kind-${t.kind}">${kindChip[t.kind]}</span><span class="chip primary">Wk ${t.week}</span><span class="chip">${t.hours}h</span></span>
        </label>`).join("")}
        ${item.resources.length ? `<div class="resources"><span class="muted">Free resources:</span>${item.resources.map(x =>
          `<a href="${esc(x.url)}" target="_blank" rel="noopener">${esc(x.title)} ↗</a>`).join("")}</div>` : ""}
      </div>`).join("")}
    </div>`).join("")}`;

  view.querySelectorAll("[data-task]").forEach(box => box.addEventListener("change", async () => {
    const next = await api("/api/progress", { task_id: box.dataset.task, done: box.checked });
    if (box.checked) toast("Task completed ✓ — readiness updated");
    const y = window.scrollY;
    renderRoadmap(next);
    window.scrollTo(0, y);
  }));
}

